def criterion(x, y):
    """
    Calculate the mean square error between two complex numbers of type torch.complex64.

    Args:
    x (torch.complex64): The first complex number.
    y (torch.complex64): The second complex number.

    Returns:
    mse (torch.float32): The mean square error between x and y.
    """
    # Calculate the squared difference between real and imaginary parts
    real_diff = torch.square(torch.real(x) - torch.real(y))
    imag_diff = torch.square(torch.imag(x) - torch.imag(y))

    # Calculate the mean square error
    mse = torch.mean(real_diff + imag_diff)
    #return (0.5*(x - y)**2).mean(dtype=torch.complex64)
    return mse

