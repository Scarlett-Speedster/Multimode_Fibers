# Function to calculate fidelity
def calculate_fidelity(outputs, ground_truths):
    fidelities = []

    # Iterate through each output and ground truth pair
    for output, ground_truth in zip(outputs, ground_truths):
        # Normalize output and ground truth samples
        output_norm = output / torch.norm(output)
        ground_truth_norm = ground_truth / torch.norm(ground_truth)

        # Calculate inner product
        inner_product = torch.dot(output_norm, ground_truth_norm)

        # Calculate fidelity (square of absolute value of inner product)
        fidelity = torch.abs(inner_product) ** 2

        # Append fidelity to list
        fidelities.append(fidelity.item())  # Convert to scalar value

    return fidelities

